# -*- coding: utf-8 -*-
"""A global mutation run over Hermod's DNS resource records.

Stryker.NET cannot do this job here: 4.16 and 5.0 both die with a
NullReferenceException inside their own mutation injector, on a single file, at
every mutation level. So the catalogue is generated by genmut.py and run by the
same harness this repository has used all along — BASELINE first, the marker
read back from disk, and the timestamp of the assembly the test host actually
loads.

The one thing Stryker does that this cannot is mutation switching: it compiles
every mutant into one assembly and selects at runtime. Here each mutant is a
build. Measured at nine seconds a cycle, which is what makes 672 of them a
two-hour job rather than a two-day one.

Results are appended as they happen, so a partial run is still a readable one,
and a rerun skips what is already recorded.
"""

import io
import os
import re
import subprocess
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import genmut

import os as _os

# The repository this script lives in, found from the script rather than
# written down: build/mutation/<this file>  ->  two levels up.
ROOT = _os.path.abspath(_os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "..", ".."))
SRCROOT = os.path.join(ROOT, r"libs\Hermod\Hermod")
RECORDS = os.path.join(SRCROOT, r"DNS\ResourceRecords")

PROJ = os.path.join(ROOT, r"conformance\DNSConformance.ResourceRecords.Tests\DNSConformance.ResourceRecords.Tests.csproj")
DLL  = os.path.join(ROOT, r"conformance\DNSConformance.ResourceRecords.Tests\bin\Debug\net10.0\org.GraphDefined.Vanaheimr.Hermod.dll")

RESULTS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results", "records-pass1.tsv")

EXPECTED_TESTS = 226

FAILED = re.compile(r"(?:Fehler|Failed):\s*(\d+)")
TOTAL  = re.compile(r"(?:gesamt|total):\s*(\d+)", re.IGNORECASE)


def run(cmd, timeout=900):
    return subprocess.run(cmd, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=timeout)


def build():
    return run(["dotnet", "build", PROJ, "-v", "q", "--nologo"])


def run_tests():
    out = run(["dotnet", "test", PROJ, "--no-build", "-v", "q", "--nologo"]).stdout or ""
    f, t = FAILED.search(out), TOTAL.search(out)
    return (int(f.group(1)), int(t.group(1))) if f and t else None


def read(path):
    with open(path, "rb") as f:
        raw = f.read()
    bom = raw.startswith(b"\xef\xbb\xbf")
    text = raw.decode("utf-8-sig" if bom else "utf-8")
    nl = "\r\n" if "\r\n" in text else "\n"
    return text, nl, bom


def write(path, text, nl, bom):
    data = text.replace("\r\n", "\n").replace("\n", nl).encode("utf-8")
    if bom:
        data = b"\xef\xbb\xbf" + data
    with open(path, "wb") as f:
        f.write(data)


def already_done():
    done = set()
    if os.path.exists(RESULTS):
        for line in io.open(RESULTS, encoding="utf-8"):
            parts = line.rstrip("\n").split("\t")
            if len(parts) >= 3:
                done.add((parts[0], parts[1], parts[2]))
    return done


def record(rel, line_no, op, verdict, detail):
    with io.open(RESULTS, "a", encoding="utf-8") as f:
        f.write("%s\t%s\t%s\t%s\t%s\n" % (rel, line_no, op, verdict, detail))


def main():

    if not os.path.exists(DLL):
        sys.exit("guard is broken, no such assembly: " + DLL)

    print("guard watches " + DLL)

    b = build()
    if b.returncode != 0:
        sys.exit("baseline build failed:\n" + (b.stdout or "")[-2000:])

    baseline = run_tests()
    if baseline is None:
        sys.exit("baseline: could not parse the test summary")
    if baseline != (0, EXPECTED_TESTS):
        sys.exit("baseline is not clean: failed=%d total=%d, expected 0 of %d"
                 % (baseline[0], baseline[1], EXPECTED_TESTS))

    print("baseline: %d tests, 0 failures - the parser sees a green run" % baseline[1])

    mutants = genmut.main(RECORDS, SRCROOT)

    # Busiest file first: if the run is cut short, the most-mutated file is the
    # one already covered.
    order = {}
    for rel, _, _, _, _ in mutants:
        order[rel] = order.get(rel, 0) + 1
    mutants.sort(key=lambda m: (-order[m[0]], m[0], m[1]))

    done = already_done()
    print("\n%d mutants, %d already recorded\n" % (len(mutants), len(done)))

    started = time.time()
    counts  = {}
    limit   = int(sys.argv[1]) if len(sys.argv) > 1 else 0
    ran     = 0

    for n, (rel, line_no, op, original, mutated) in enumerate(mutants, start=1):

        key = (rel, str(line_no), op)
        if key in done:
            continue

        path = os.path.join(SRCROOT, rel.replace("/", "\\"))
        text, nl, bom = read(path)

        lines = text.replace("\r\n", "\n").split("\n")

        if line_no > len(lines) or lines[line_no - 1] != original:
            record(rel, line_no, op, "SETUP-ERROR", "line moved or did not match")
            continue

        lines[line_no - 1] = mutated + "  /*MUTANT*/"
        mutated_text = "\n".join(lines)

        try:

            write(path, mutated_text, nl, bom)

            back, _, _ = read(path)
            if "/*MUTANT*/" not in back:
                record(rel, line_no, op, "SETUP-ERROR", "marker not on disk")
                continue

            before = os.path.getmtime(DLL)

            b = build()
            if b.returncode != 0:
                record(rel, line_no, op, "BUILD-FAILED", "not a viable mutant")
                counts["BUILD-FAILED"] = counts.get("BUILD-FAILED", 0) + 1
                continue

            if os.path.getmtime(DLL) <= before:
                record(rel, line_no, op, "STALE-BINARY", "the loaded assembly was not rebuilt")
                counts["STALE-BINARY"] = counts.get("STALE-BINARY", 0) + 1
                continue

            counted = run_tests()
            if counted is None:
                record(rel, line_no, op, "PARSE-ERROR", "no summary line")
                counts["PARSE-ERROR"] = counts.get("PARSE-ERROR", 0) + 1
                continue

            failed, total = counted

            if total != EXPECTED_TESTS:
                verdict, detail = "SETUP-ERROR", "%d tests ran, expected %d" % (total, EXPECTED_TESTS)
            elif failed > 0:
                verdict, detail = "KILLED", "%d of %d failed" % (failed, total)
            else:
                verdict, detail = "SURVIVED", "0 of %d failed - %s" % (total, original.strip()[:110])

            record(rel, line_no, op, verdict, detail)
            counts[verdict] = counts.get(verdict, 0) + 1

            if verdict == "SURVIVED":
                print("  SURVIVED  %s:%d  %s" % (rel, line_no, op))

        except subprocess.TimeoutExpired:
            record(rel, line_no, op, "TIMEOUT", "the test run did not finish")
            counts["TIMEOUT"] = counts.get("TIMEOUT", 0) + 1

        finally:
            write(path, text, nl, bom)

        ran += 1
        if limit and ran >= limit:
            print("smoke test: stopping after %d mutants" % ran)
            break

        if n % 25 == 0:
            elapsed = time.time() - started
            print("[%d/%d]  %.0f min elapsed  %s" % (n, len(mutants), elapsed / 60, counts))

    print()
    print("=" * 80)
    killed   = counts.get("KILLED", 0)
    survived = counts.get("SURVIVED", 0)
    viable   = killed + survived
    for verdict, n in sorted(counts.items(), key=lambda kv: -kv[1]):
        print("%-14s %4d" % (verdict, n))
    if viable:
        print()
        print("mutation score: %d / %d = %.1f%%" % (killed, viable, 100.0 * killed / viable))
    print("=" * 80)

    build()
    print("sources restored and rebuilt")


if __name__ == "__main__":
    main()
